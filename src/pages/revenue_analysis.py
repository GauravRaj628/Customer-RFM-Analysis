def compute_pareto_curve(rfm_df: pd.DataFrame) -> tuple[pd.DataFrame, float, float, float]:
    """
    Compute Pareto / Lorenz curve data and revenue concentration metrics.

    Returns
    -------
    tuple[pd.DataFrame, float, float, float]
        - curve_df: DataFrame with ['pct_customers', 'pct_revenue']
        - top_10_share: % of revenue generated by top 10% customers
        - top_20_share: % of revenue generated by top 20% customers
        - gini_coef: Gini coefficient of spending inequality
    """
    if rfm_df.empty or "monetary" not in rfm_df.columns:
        return pd.DataFrame(), 0.0, 0.0, 0.0

    sorted_df = rfm_df.sort_values(by="monetary", ascending=False).reset_index(drop=True)
    n = len(sorted_df)
    total_rev = sorted_df["monetary"].sum()

    if total_rev == 0 or n == 0:
        return pd.DataFrame(), 0.0, 0.0, 0.0

    sorted_df["cum_revenue"] = sorted_df["monetary"].cumsum()
    sorted_df["pct_revenue"] = (sorted_df["cum_revenue"] / total_rev) * 100.0
    sorted_df["pct_customers"] = (np.arange(1, n + 1) / n) * 100.0

    # Top 10% and 20% indices
    idx_10 = int(round(n * 0.10)) - 1
    idx_20 = int(round(n * 0.20)) - 1
    top_10_share = float(sorted_df["pct_revenue"].iloc[max(0, idx_10)])
    top_20_share = float(sorted_df["pct_revenue"].iloc[max(0, idx_20)])

    # Gini coefficient calculation (ascending order)
    y = np.sort(sorted_df["monetary"].values)
    index = np.arange(1, n + 1)
    gini = float((2 * np.sum(index * y) / (n * np.sum(y))) - (n + 1) / n)

    # Insert origin (0, 0)
    origin = pd.DataFrame([{"pct_customers": 0.0, "pct_revenue": 0.0}])
    curve_df = pd.concat([origin, sorted_df[["pct_customers", "pct_revenue"]]], ignore_index=True)

    return curve_df, top_10_share, top_20_share, gini


def build_pareto_chart(curve_df: pd.DataFrame, top_20_share: float) -> go.Figure:
    """Build interactive Pareto 80/20 Lorenz curve."""
    if curve_df.empty:
        return go.Figure()

    fig = go.Figure()

    # Perfect equality baseline (45-degree diagonal)
    fig.add_trace(
        go.Scatter(
            x=[0, 100],
            y=[0, 100],
            mode="lines",
            name="Equal Distribution (1:1)",
            line=dict(color="#94A3B8", dash="dash", width=1.5),
            hoverinfo="skip",
        )
    )

    # Actual customer revenue concentration curve
    fig.add_trace(
        go.Scatter(
            x=curve_df["pct_customers"],
            y=curve_df["pct_revenue"],
            mode="lines",
            name="Actual Spend Concentration",
            line=dict(color="#172554", width=3),
            fill="tonexty",
            fillcolor="rgba(37, 99, 235, 0.08)",
            hovertemplate="Top %{x:.1f}% Customers<br>Generate %{y:.1f}% Revenue<extra></extra>",
        )
    )

    # Top 20% reference marker
    fig.add_trace(
        go.Scatter(
            x=[20.0],
            y=[top_20_share],
            mode="markers+text",
            name="Top 20% Cut-off",
            text=[f"Top 20% → {top_20_share:.1f}%"],
            textposition="top left",
            textfont=dict(family=FONT_FAMILY, size=11, color="#DC2626"),
            marker=dict(color="#DC2626", size=9, symbol="diamond"),
            hoverinfo="skip",
        )
    )

    fig.add_vline(x=20, line_dash="dot", line_color="#DC2626", line_width=1.5)
    fig.add_hline(y=top_20_share, line_dash="dot", line_color="#DC2626", line_width=1.5)

    fig.update_layout(
        template="plotly_white",
        font=dict(family=FONT_FAMILY),
        title=dict(text="Pareto 80/20 Revenue Concentration (Lorenz Curve)", font=dict(family=FONT_FAMILY, size=14, color="#0F172A")),
        xaxis=dict(title=dict(text="Cumulative % of Customers (Highest to Lowest Spend)"), range=[0, 102], gridcolor="#F1F5F9"),
        yaxis=dict(title=dict(text="Cumulative % of Gross Revenue"), range=[0, 102], gridcolor="#F1F5F9"),
        legend=dict(
            orientation="h",
            yanchor="bottom",
            y=-0.24,
            xanchor="center",
            x=0.5,
            font=dict(family=FONT_FAMILY, size=11, color="#475569"),
        ),
        margin=dict(l=40, r=20, t=45, b=40),
        height=380,
    )
    return fig


def build_segment_timeline_chart(seg_rev_df: pd.DataFrame) -> go.Figure:
    """Build stacked bar chart of monthly revenue contribution by segment."""
    if seg_rev_df.empty:
        return go.Figure()

    fig = px.bar(
        seg_rev_df,
        x="year_month",
        y="revenue",
        color="customer_segment",
        color_discrete_map=SEGMENT_COLOURS,
        title="Monthly Revenue Contribution by Customer Segment",
        labels={"year_month": "Month", "revenue": "Gross Revenue (₹)", "customer_segment": "Segment"},
    )
    fig.update_layout(
        template="plotly_white",
        font=dict(family=FONT_FAMILY),
        title=dict(font=dict(family=FONT_FAMILY, size=14, color="#0F172A")),
        xaxis=dict(title=dict(text="Month (YYYY-MM)"), tickangle=-30, gridcolor="#F1F5F9"),
        yaxis=dict(title=dict(text="Gross Revenue (₹)"), gridcolor="#F1F5F9"),
        legend=dict(
            orientation="h",
            yanchor="bottom",
            y=-0.30,
            xanchor="center",
            x=0.5,
            font=dict(family=FONT_FAMILY, size=11, color="#475569"),
        ),
        margin=dict(l=40, r=20, t=45, b=40),
        height=380,
    )
    return fig


def build_cohort_heatmap(cohort_matrix: pd.DataFrame) -> go.Figure:
    """Build interactive acquisition cohort revenue retention heatmap."""
    if cohort_matrix.empty:
        return go.Figure()

    fig = go.Figure(
        data=go.Heatmap(
            z=cohort_matrix.values,
            x=[f"Month +{col}" for col in cohort_matrix.columns],
            y=cohort_matrix.index.tolist(),
            colorscale="Blues",
            text=[[f"₹{val:,.0f}" if not pd.isna(val) and val > 0 else "-" for val in row] for row in cohort_matrix.values],
            texttemplate="%{text}",
            textfont=dict(family=FONT_FAMILY, size=10),
            colorbar=dict(title=dict(text="Revenue (₹)", font=dict(family=FONT_FAMILY, size=11))),
            hovertemplate="<b>Cohort: %{y} | %{x}</b><br>Spend: ₹%{z:,.2f}<extra></extra>",
        )
    )
    fig.update_layout(
        template="plotly_white",
        font=dict(family=FONT_FAMILY),
        title=dict(text="Customer Acquisition Cohort Revenue Heatmap", font=dict(family=FONT_FAMILY, size=14, color="#0F172A")),
        xaxis=dict(title=dict(text="Months Elapsed Since Acquisition")),
        yaxis=dict(title=dict(text="Acquisition Cohort (First Purchase)")),
        margin=dict(l=40, r=20, t=45, b=40),
        height=380,
    )
    return fig


def render() -> None:
    """Render the Revenue Analysis & Cohort LTV screen."""
    render_page_header(
        title="Revenue Concentration & Cohort Lifetime Value",
        subtitle="Step 7 of 8: Analyze revenue distribution, Pareto 80/20 concentration, and customer acquisition cohorts",
        breadcrumb="Revenue Intelligence",
    )

    # Ensure valid data exists in session state
    if (
        "valid_df" not in st.session_state
        or st.session_state["valid_df"] is None
        or "rfm_df" not in st.session_state
        or st.session_state["rfm_df"] is None
    ):
        if Path(DEFAULT_DATASET_PATH).exists():
            process_and_cache_dataset(DEFAULT_DATASET_PATH, source_label="Default Synthetic Dataset")

    valid_df = st.session_state.get("valid_df")
    rfm_df = st.session_state.get("rfm_df")

    if valid_df is None or valid_df.empty or rfm_df is None or rfm_df.empty:
        render_empty_state("No transaction or RFM data available. Please upload a dataset in Data Upload.")
        return

    # ── Pareto Metrics & Concentration KPIs ────────────────────────────────────
    curve_df, top_10_share, top_20_share, gini_coef = compute_pareto_curve(rfm_df)
    total_rev = float(rfm_df["monetary"].sum())

    r1, r2, r3, r4 = st.columns(4)
    with r1:
        render_kpi_card("Total Valid Revenue", f"₹{total_rev:,.2f}", icon="💰")
    with r2:
        render_kpi_card("Top 20% Revenue Share", f"{top_20_share:.1f}%", icon="🎯", help_text="Percentage of gross revenue generated by the top 20% highest spending customers.")
    with r3:
        render_kpi_card("Top 10% Revenue Share", f"{top_10_share:.1f}%", icon="🏆", help_text="Percentage of gross revenue generated by the top 10% highest spending customers.")
    with r4:
        render_kpi_card("Gini Concentration Ratio", f"{gini_coef:.2f}", icon="📈", help_text="0 = perfect equality; 1 = maximum concentration of revenue among few customers.")

    st.write("")
    st.divider()

    # ── Section 1: Pareto Lorenz Curve & Segment Timeline ─────────────────────
    st.markdown("### 📊 Revenue Concentration & Temporal Trajectory")
    col_pareto, col_timeline = st.columns(2)

    with col_pareto:
        fig_pareto = build_pareto_chart(curve_df, top_20_share)
        st.plotly_chart(fig_pareto, use_container_width=True)

    with col_timeline:
        seg_rev_df = compute_revenue_by_segment(rfm_df, valid_df)
        fig_timeline = build_segment_timeline_chart(seg_rev_df)
        st.plotly_chart(fig_timeline, use_container_width=True)

    st.write("")

    # ── Section 2: Acquisition Cohort Revenue Heatmap ──────────────────────────
    st.markdown("### 🗓️ Customer Acquisition Cohort Revenue Heatmap")
    st.caption("Tracks subsequent monthly revenue generated by customers grouped by their first purchase month.")
    cohort_matrix = compute_cohort_revenue(valid_df)
    fig_cohort = build_cohort_heatmap(cohort_matrix)
    st.plotly_chart(fig_cohort, use_container_width=True)

    st.write("")

    # ── Section 3: Revenue Tier Distribution Table ─────────────────────────────
    st.markdown("### 🏛️ Customer Spend Concentration Tiers")
    sorted_rfm = rfm_df.sort_values(by="monetary", ascending=False).reset_index(drop=True)
    n = len(sorted_rfm)

    tiers = [
        ("Top 5% (VIP Tier)", 0.0, 0.05),
        ("Next 15% (High Value)", 0.05, 0.20),
        ("Next 30% (Mid Tier)", 0.20, 0.50),
        ("Bottom 50% (Long Tail)", 0.50, 1.00),
    ]

    tier_rows = []
    for tier_name, start_pct, end_pct in tiers:
        start_idx = int(round(n * start_pct))
        end_idx = int(round(n * end_pct))
        slice_df = sorted_rfm.iloc[start_idx:end_idx]
        cust_cnt = len(slice_df)
        tier_rev = float(slice_df["monetary"].sum())
        rev_pct = (tier_rev / total_rev * 100) if total_rev > 0 else 0.0
        avg_spend = (tier_rev / cust_cnt) if cust_cnt > 0 else 0.0
        avg_freq = float(slice_df["frequency"].mean()) if cust_cnt > 0 else 0.0

        tier_rows.append({
            "Customer Tier": tier_name,
            "Customer Count": f"{cust_cnt:,}",
            "Share of Base (%)": f"{(cust_cnt / n * 100):.1f}%",
            "Total Revenue (₹)": f"₹{tier_rev:,.2f}",
            "Revenue Share (%)": f"{rev_pct:.1f}%",
            "Avg Spend / Customer": f"₹{avg_spend:,.2f}",
            "Avg Orders": f"{avg_freq:.1f}",
        })

    tier_df = pd.DataFrame(tier_rows)
    st.dataframe(tier_df, use_container_width=True, hide_index=True)

    st.write("")

    # ── Next Step Callout ──────────────────────────────────────────────────────
    st.info(
        "💡 **Revenue Inspected:** Proceed to **💡 Business Insights** from the sidebar to access executive "
        "summary recommendations, cohort action plans, and automated marketing strategies.",
        icon="👉",
    )
